"""
Markdown investigation report (indicators defanged for safe sharing).
"""

from typing import Any, Dict, List

from app.reports.common import defang, indicator_rows, matched_rules


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_markdown(result: Dict[str, Any]) -> str:
    risk = result.get("risk_assessment") or {}
    report = result.get("analyst_report") or {}
    lines: List[str] = [
        f"# ReconIQ Investigation Report",
        "",
        f"**Investigation:** `{result['investigation_id']}`  ",
        f"**Completed:** {result.get('timestamp', '')}  ",
        f"**Source:** {result.get('source_name') or result.get('source_type', 'raw_text')}",
        "",
        "## Verdict",
        "",
        "| Score | Severity | Classification | Confidence |",
        "|---|---|---|---|",
        f"| {risk.get('total_score', 0):.0f}/100 | {risk.get('severity', 'n/a')} | "
        f"{risk.get('classification', 'n/a').replace('_', ' ')} | {round((risk.get('confidence') or 0) * 100)}% |",
        "",
    ]
    if report:
        lines += ["## Analyst Summary", "", report.get("summary", ""), ""]
        if report.get("key_findings"):
            lines += ["**Key findings**", ""] + [f"- {defang_inline(k)}" for k in report["key_findings"]] + [""]
        if report.get("recommended_actions"):
            lines += ["**Recommended actions**", ""] + [f"{i}. {a}" for i, a in enumerate(report["recommended_actions"], 1)] + [""]
        lines += [f"_{report.get('disclaimer', '')}_", ""]

    findings = sorted(risk.get("findings", []), key=lambda f: -f.get("score_impact", 0))
    lines += ["## Findings", ""]
    if findings:
        lines += ["| Rule | Finding | Severity | Points |", "|---|---|---|---|"]
        lines += [f"| {f.get('rule_id', '')} | **{_cell(f['title'])}** — {_cell(defang_inline(f['description']))} | "
                  f"{f.get('severity', '')} | +{f.get('score_impact', 0):g} |" for f in findings]
    else:
        lines.append("No rules produced findings.")
    lines.append("")

    techniques = risk.get("mitre_techniques", [])
    if techniques:
        lines += ["## MITRE ATT&CK", "", "| Technique | Name | Tactic |", "|---|---|---|"]
        lines += [f"| [{t['id']}]({t['url']}) | {t['name']} | {t['tactic']} |" for t in techniques] + [""]

    rows = indicator_rows(result)
    lines += ["## Indicators", ""]
    if rows:
        lines += ["| Type | Indicator (defanged) | Validation | Threat intel |", "|---|---|---|---|"]
        lines += [f"| {t} | `{_cell(defang(v))}` | {val} | {_cell(intel)} |" for t, v, val, intel in rows]
    else:
        lines.append("No indicators extracted.")
    lines.append("")

    email = (result.get("ingestion") or {}).get("email")
    if email:
        auth = ", ".join(f"{k.upper()}={v}" for k, v in (email.get("authentication") or {}).items()) or "not present"
        lines += ["## Email Analysis", "",
                  f"- **Subject:** {_cell(email.get('subject') or '')}",
                  f"- **From:** {_cell(email.get('display_name') or '')} <{defang(email.get('from') or '')}>",
                  f"- **Reply-To:** {defang(email.get('reply_to') or '—')}",
                  f"- **Authentication:** {auth}",
                  f"- **Relay IPs:** {', '.join(defang(i) for i in email.get('received_ips', [])) or '—'}",
                  f"- **Attachments:** {', '.join(a.get('filename', '') for a in email.get('attachments', [])) or 'none'}", ""]
    file_info = (result.get("ingestion") or {}).get("file")
    if file_info and not email:
        lines += ["## File Analysis", "",
                  f"- **Name:** {file_info.get('filename')} ({file_info.get('kind')}, {file_info.get('size')} bytes)",
                  f"- **SHA-256:** `{file_info.get('sha256')}`", ""]

    lines += ["## Rule Audit (matched)", "", "| Rule | Name | Weight |", "|---|---|---|"]
    lines += [f"| {r['rule_id']} | {r['rule_name']} | {r['weight']:g} |" for r in matched_rules(result)] or ["| — | none | — |"]
    lines += ["", "---", "_Generated by ReconIQ — Evidence. Intelligence. Trust._", ""]
    return "\n".join(lines)


def defang_inline(text: str) -> str:
    """Defangs URL schemes in free text without touching ordinary prose."""
    return text.replace("https://", "hxxps://").replace("http://", "hxxp://")
