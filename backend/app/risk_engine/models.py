"""
ReconIQ Risk Engine Data Models

Purpose:
Reusable Pydantic v2 data models for the Deterministic Risk Engine.

Responsibilities:
- Encapsulate individual risk findings, applied detection rules, confidence ratings, and aggregated assessment reports

Future Extension Notes:
- Export support for STIX 2.1 Risk/Sighting objects and JSON investigation exports.
"""

from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class RiskFinding(BaseModel):
    """
    Individual risk indicator or finding generated by a rule evaluation match.
    """
    finding_id: str = Field(..., description="Unique identifier for the finding")
    title: str = Field(..., description="Short descriptive title of the finding")
    description: str = Field(..., description="Detailed explanation of the risk finding")
    severity: str = Field(..., description="Severity classification (INFORMATIONAL, LOW, MEDIUM, HIGH, CRITICAL)")
    score_impact: float = Field(..., description="Numeric score contribution of this finding")
    artifact: Optional[str] = Field(default=None, description="Specific artifact string associated with the finding")
    rule_id: Optional[str] = Field(default=None, description="ID of the rule that produced the finding")
    categories: List[str] = Field(default_factory=list, description="Threat taxonomy categories evidenced by the finding")
    mitre_techniques: List[Dict[str, str]] = Field(default_factory=list, description="MITRE ATT&CK technique references")
    cwes: List[Dict[str, str]] = Field(default_factory=list, description="CWE weakness references")


class AppliedRule(BaseModel):
    """
    Record of a detection rule evaluated during a risk assessment.
    """
    rule_id: str = Field(..., description="Unique rule ID (e.g. RULE_VAL_001)")
    rule_name: str = Field(..., description="Human-readable rule name")
    description: str = Field(..., description="Rule logic description")
    weight: float = Field(..., description="Numeric risk weight assigned to this rule")
    severity: str = Field(..., description="Rule severity level")
    matched: bool = Field(..., description="Whether the rule conditions matched the evidence")
    evidence_context: Dict[str, Any] = Field(
        default_factory=dict,
        description="Matched evidence context or metadata"
    )


class RiskSummary(BaseModel):
    """
    Condensed summary of risk assessment metrics.
    """
    total_score: float = Field(..., ge=0.0, le=100.0, description="Final aggregate risk score (0-100)")
    severity: str = Field(..., description="Final severity rating")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Overall confidence rating (0.0 - 1.0)")
    rule_count: int = Field(..., description="Total rules evaluated")
    triggered_rules_count: int = Field(..., description="Number of rules that triggered a match")


class RiskAssessment(BaseModel):
    """
    Complete, deterministic Risk Assessment report returned by RiskScorer.
    """
    total_score: float = Field(..., ge=0.0, le=100.0, description="Final capped risk score (0-100)")
    severity: str = Field(..., description="Severity classification (INFORMATIONAL, LOW, MEDIUM, HIGH, CRITICAL)")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Calculated assessment confidence rating (0.0 to 1.0)")
    findings: List[RiskFinding] = Field(default_factory=list, description="Categorized risk findings")
    applied_rules: List[AppliedRule] = Field(default_factory=list, description="Log of all evaluated rules")
    artifact_breakdown: Dict[str, int] = Field(default_factory=dict, description="Artifact count breakdown")
    classification: str = Field(default="unknown", description="Primary threat category (highest weighted)")
    threat_categories: List[str] = Field(default_factory=list, description="All evidenced threat categories, ranked")
    mitre_techniques: List[Dict[str, str]] = Field(default_factory=list, description="Aggregated MITRE ATT&CK techniques")
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 UTC timestamp of assessment completion"
    )
    execution_time_ms: float = Field(default=0.0, description="Assessment execution latency in milliseconds")
